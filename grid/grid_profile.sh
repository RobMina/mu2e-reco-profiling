#!/bin/bash
# grid_profile.sh <OUTROOT> -- grid worker: run ONE reco_profile test (plus, for art-timing jobs, its paired baseline on
# the same node first) and copy the profile outputs to pnfs.
#   OUTROOT  pnfs dir of the arm, e.g. $RP_PNFS/kkmain
#   env:  TESTS        comma list of test ids; this job runs TESTS[PROCESS] (PROCESS from jobsub -N, default 0)
#         CODE_TARBALL pnfs path of the area's muse tarball (Code.tar.bz2, has Code/setup.sh)
#         AUX_TARBALL  pnfs path of aux.tgz (this repository's tables and fcl, plus the KPP calibration set if given),
#                      made by submit_profile.sh
#         N (override events of the test; the paired baseline always uses its own tests.txt N), NSKIP,
#         FORCE=1 (rerun even if done.txt exists)
#         PAIR         1 (default) = run the baseline from pairs.txt first, same node, outputs in OUTROOT/<id>/base_<bid>/;
#                      0 = test only. Ignored (off) when TOOL is set.
#         EVENT        run:subrun:event -- start the source at that event (RootInput firstRun/firstSubRun/firstEvent)
#                      and process N events (default 1); outputs get suffix _evt<event>. For single pathological events.
#         TAG          suffix for the output dir (<id>_<TAG>), e.g. smoke for short construction checks
#         DUMP         callgrind dump granularity: event (default; one dump per event, .1 = init) or run (.1 = init up to
#                      the start of the run, final = all events + end job; end job is ~1 % of a few-hundred-event run)
#         TOOL         empty = art timing; callgrind | massif | dhat = run under valgrind (outputs OUTROOT/<id>_<tool>/,
#                      prof_tool.fcl instead of prof_services.fcl). VGOPTS adds valgrind options.
# Same job.fcl composition and output names as run_profile.sh, so the recoprof tools read both.
# No `set -u`/`set -e` (setupmu2e-art.sh); no timeout around mu2e (jobsub --expected-lifetime owns the runtime).
OUTROOT=${1:?need OUTROOT (pnfs)}
IFS=, read -ra TL <<< "${TESTS:?need TESTS}"
ID=${TL[${PROCESS:-0}]}
[ -z "$ID" ] && { echo "ERROR: no test at PROCESS=${PROCESS:-0} in TESTS=$TESTS"; exit 1; }
OUT=$OUTROOT/$ID${TOOL:+_$TOOL}${EVENT:+_evt${EVENT##*:}}${TAG:+_$TAG}
echo "=== grid_profile: $ID  host=$(hostname)  $(date -u)  cluster=${CLUSTER:-?}.${PROCESS:-0}"

source /cvmfs/mu2e.opensciencegrid.org/setupmu2e-art.sh >/dev/null 2>&1
setup muse >/dev/null 2>&1
setup ifdhc >/dev/null 2>&1 || true
which ifdh >/dev/null 2>&1 || { echo "ERROR: no ifdh"; exit 2; }

if [ "${FORCE:-0}" != 1 ] && ifdh ls "$OUT/done.txt" >/dev/null 2>&1; then echo "SKIP: $OUT/done.txt exists"; exit 0; fi

TOP=$PWD
t0=$SECONDS
ifdh cp "$CODE_TARBALL" ./Code.tar.bz2 && tar xjf ./Code.tar.bz2 && rm -f ./Code.tar.bz2 || { echo "STAGE/UNTAR code FAILED"; exit 2; }
ifdh cp "$AUX_TARBALL" ./aux.tgz && mkdir -p aux && tar xzf ./aux.tgz -C aux && rm -f ./aux.tgz || { echo "STAGE aux FAILED"; exit 2; }
source ./Code/setup.sh >/dev/null 2>&1
which mu2e >/dev/null 2>&1 || { echo "ERROR: mu2e not on PATH after Code/setup.sh"; exit 2; }
T_CODE=$((SECONDS-t0))

HERE=$TOP/aux/reco_profile
KC=""; [ -d "$TOP/aux/kpp_calib" ] && KC=$TOP/aux/kpp_calib
export FHICL_FILE_PATH="$HERE/fcl:$HERE/fcl/kpp${KC:+:$KC}:$FHICL_FILE_PATH"
[ -n "$KC" ] && export MU2E_SEARCH_PATH="$KC:$MU2E_SEARCH_PATH"
KEEPERS=" $(awk '!/^#/{print $5}' "$HERE/tests.txt" | tr '\n' ' ') "

# run_one <test-id> <pnfs out dir> <events override or ""> <tool or ""> <keep-art 0|1> : stage input, run, copy out
run_one() {
  local id=$1 out=$2 nov=$3 tool=$4 keepok=$5
  local base db vars input ndef thr n src rc=99 failed="" dir=$TOP/run_$id
  read -r _ base db vars input ndef thr < <(awk -v id="$id" '$1==id' "$HERE/tests.txt")
  [ -z "$base" ] && { echo "ERROR: unknown test $id"; return 1; }
  n=${nov:-$ndef}
  [ -n "$EVENT" ] && [ "$id" = "$ID" ] && n=${nov:-1}
  case "$input" in
    I[0-9]*) src=$(awk -v k="$input" '$1==k{print $2}' "$HERE/inputs.txt") ;;
    S:*)     src=$OUTROOT/${input#S:}/reco.art ;;
    U:*)     src=$OUTROOT/${input#U:}/dig.art ;;
    *)       src=$input ;;
  esac
  [ -z "$src" ] && { echo "ERROR: no input for $id"; return 1; }
  mkdir -p "$dir" && cd "$dir" || return 2
  # stage the input to local disk so the timed job does not include dCache reads
  local t0=$SECONDS
  ifdh cp "$src" ./input.art || { echo "STAGE input FAILED: $src"; cd "$TOP"; return 2; }
  local tin=$((SECONDS-t0))
  {
    echo "# generated by grid_profile.sh $id ($(date -Is))"
    echo "#include \"base_$base.fcl\""
    [ "$vars" != "-" ] && for v in ${vars//,/ }; do echo "#include \"v_$v.fcl\""; done
    echo "#include \"db_$db.fcl\""
    if [ -n "$tool" ]; then echo "#include \"prof_tool.fcl\""; else echo "#include \"prof_services.fcl\""; fi
    if [ -n "$EVENT" ] && [ "$id" = "$ID" ]; then
      IFS=: read -r er es ee <<< "$EVENT"
      echo "source.firstRun : $er"; echo "source.firstSubRun : $es"; echo "source.firstEvent : $ee"
    fi
  } > job.fcl
  local threads=""
  [ -n "$thr" ] && [ "$thr" != "1" ] && threads="--nthreads $thr --nschedules $thr"
  {
    echo "event=${EVENT:-all}"
    echo "test=$id job_test=$ID role=$([ "$id" = "$ID" ] && echo test || echo baseline) arm=$(basename "$OUTROOT") host=$(hostname) site=${GLIDEIN_Site:-?} n=$n nskip=${NSKIP:-0} threads=${thr:-1}"
    echo "cluster=${CLUSTER:-?}.${PROCESS:-0} code=$CODE_TARBALL aux=$AUX_TARBALL"
    echo "input=$src stage_input_s=$tin stage_code_s=$T_CODE input_mb=$(du -m input.art | cut -f1)"
    echo "cpu=$(grep -m1 'model name' /proc/cpuinfo | cut -d: -f2) ncpu_node=$(nproc --all) ncpu_job=$(nproc) load=$(cut -d' ' -f1-3 /proc/loadavg)"
    echo "tool=${tool:-none} dump=${DUMP:-event} vgopts=${VGOPTS:-} perf=$(command -v perf || echo none) perf_event_paranoid=$(cat /proc/sys/kernel/perf_event_paranoid 2>/dev/null)"
  } > meta.txt
  fhicl-dump -c job.fcl > job.cfg 2>&1 || { echo "FATAL: fhicl-dump failed for $id"; tail -20 job.cfg; failed=fhicl; }
  if [ -z "$failed" ]; then
    local timecmd="" vg=""
    [ -x /usr/bin/time ] && timecmd="/usr/bin/time -v -o time.txt" || echo "no /usr/bin/time on this node" > time.txt
    # callgrind dumps once before the event loop (file .1 = initialisation) and at exit (event loop)
    case "$tool" in
      "")        vg="" ;;
      callgrind)
        if [ "${DUMP:-event}" = run ]; then
          dumps="--dump-before=*EventProcessor::process<(art::Level)2>*"
        else
          dumps="--dump-before=art::EventProcessor::processAllEventsAsync*"
        fi
        vg="valgrind --tool=callgrind --dump-instr=yes --callgrind-out-file=callgrind.out.%p $dumps $VGOPTS" ;;
      massif)    vg="valgrind --tool=massif --massif-out-file=massif.out --depth=40 --threshold=0.5 $VGOPTS" ;;
      dhat)      vg="valgrind --tool=dhat --dhat-out-file=dhat.out $VGOPTS" ;;
      *)         echo "unknown TOOL=$tool"; cd "$TOP"; return 1 ;;
    esac
    t0=$SECONDS
    set -f   # keep the '*' in --dump-before literal
    $timecmd $vg mu2e -c job.fcl -s input.art -n "$n" ${NSKIP:+--nskip $NSKIP} $threads > log.txt 2>&1
    rc=$?; set +f
    echo "exit=$rc wall=$((SECONDS-t0))s" >> meta.txt
    ls -l ./*.art 2>/dev/null >> meta.txt
    echo "--- $id exit=$rc"; tail -15 log.txt
  fi
  rm -f input.art
  local prof=""
  if [ -n "$tool" ]; then
    for f in $(ls callgrind.out.* 2>/dev/null); do
      callgrind_annotate --threshold=99 "$f" 2>/dev/null | head -400 > "${f}.excl.txt"
      callgrind_annotate --threshold=99 --inclusive=yes "$f" 2>/dev/null | head -400 > "${f}.incl.txt"
    done
    [ -f massif.out ] && ms_print massif.out > massif.txt 2>/dev/null
    for f in $(ls callgrind.out.* 2>/dev/null | grep -v '\.txt$') massif.out dhat.out; do [ -f "$f" ] && gzip -f "$f"; done
    prof=$(ls callgrind.out.*.gz callgrind.out.*.txt massif.out.gz massif.txt dhat.out.gz 2>/dev/null)
  fi
  ifdh mkdir_p "$out" 2>/dev/null
  for f in job.fcl job.cfg log.txt time.txt timing.db memory.db $prof meta.txt; do
    [ -f "$f" ] || continue
    ifdh rm "$out/$f" >/dev/null 2>&1
    ifdh cp "$f" "$out/$f" || { echo "COPY FAILED: $id $f"; rc=5; }
  done
  # .art only for the test itself, and only if a later test reads it (S:/U: in tests.txt) or KEEP=1
  if [ "$keepok" = 1 ] && [ "$rc" = 0 ] && { [ "${KEEP:-0}" = 1 ] || [[ $KEEPERS == *" S:$id "* || $KEEPERS == *" U:$id "* ]]; }; then
    for f in reco.art dig.art; do [ -f "$f" ] && { ifdh rm "$out/$f" >/dev/null 2>&1; ifdh cp "$f" "$out/$f" || rc=5; }; done
  fi
  cd "$TOP"; rm -rf "$dir"
  return $rc
}

BID=""
[ -z "$TOOL" ] && [ "${PAIR:-1}" = 1 ] && BID=$(awk -v id="$ID" '!/^#/ && $1==id {print $2}' "$HERE/pairs.txt")
[ "$BID" = "-" ] && BID=""
brc=0
if [ -n "$BID" ]; then
  echo "=== paired baseline $BID (same node) -> $OUT/base_$BID"
  run_one "$BID" "$OUT/base_$BID" "" "" 0; brc=$?
fi
echo "=== test $ID -> $OUT"
run_one "$ID" "$OUT" "$N" "$TOOL" $([ -n "$TOOL" ] && echo 0 || echo 1); rc=$?
[ "$rc" = 0 ] && [ "$brc" != 0 ] && { echo "paired baseline $BID failed rc=$brc"; rc=6; }

# done.txt marks a complete, successful test (+ baseline); the skip check reads it, failed tests are rerun on resubmit
if [ "$rc" = 0 ]; then
  echo "$ID ok ${BID:+baseline=$BID }$(date -Is)" > done.txt
  ifdh rm "$OUT/done.txt" >/dev/null 2>&1; ifdh cp done.txt "$OUT/done.txt"
fi
echo "=== grid_profile: $ID done rc=$rc -> $OUT"
exit $rc
