#!/bin/bash
# run_profile.sh <area> <test-id> -- run ONE reco profiling job (one per GPVM) and keep its log, /usr/bin/time -v and
# TimeTracker/MemoryTracker databases under $RP_OUT/<arm>/<test-id>/ (env.sh).
#   area: muse work area (built by the user); the arm label is its basename unless ARM is set.
#   env:  N (events, default from the test table), NSKIP, KEEP=1 keeps the .art output, ARM, RP_OUT, INART (override input).
# The test table is tests.txt next to this script: id base db variants input nevents [threads].
# No `set -u` (setupmu2e-art.sh has unbound vars); start in a FRESH shell (muse refuses to re-setup).
AREA=$1; ID=$2
[ -z "$AREA" ] || [ -z "$ID" ] && { echo "usage: $0 <area> <test-id>"; exit 2; }
source "$(dirname "$0")/env.sh"
HERE=$RP_HOME
ARM=${ARM:-$(basename "$AREA")}
OUTROOT=$RP_OUT
OUT=$OUTROOT/$ARM/$ID
read -r _ BASE DB VARS INPUT NDEF THR < <(awk -v id="$ID" '$1==id' "$HERE/tests.txt")
[ -z "$BASE" ] && { echo "unknown test $ID"; exit 2; }
N=${N:-$NDEF}
INPUT=${INART:-$INPUT}
# input aliases: I1..I7 resolve to the pinned files in inputs.txt; S:<test-id> means that test's reco.art in this arm
case "$INPUT" in
  I[0-9]*) INPUT=$(awk -v k="$INPUT" '$1==k{print $2}' "$HERE/inputs.txt") ;;
  S:*)     INPUT=$OUTROOT/$ARM/${INPUT#S:}/reco.art ;;
  U:*)     INPUT=$OUTROOT/$ARM/${INPUT#U:}/dig.art ;;
esac
[ -z "$INPUT" ] && { echo "no input for $ID"; exit 2; }

source /cvmfs/mu2e.opensciencegrid.org/setupmu2e-art.sh >/dev/null 2>&1 || true
setup muse >/dev/null 2>&1
cd "$AREA" || exit 2
muse setup >/dev/null 2>&1 || true
if [ "$MUSE_WORK_DIR" != "$AREA" ]; then
  echo "FATAL: MUSE_WORK_DIR='$MUSE_WORK_DIR' is not '$AREA'; run in a fresh shell"; exit 3
fi
set +o noclobber
rp_paths
mkdir -p "$OUT" && cd "$OUT" || exit 2

# compose the job fcl: base, variants (comma list, "-" for none), database, profiling services last
FCL=$OUT/job.fcl
{
  echo "# generated by run_profile.sh $ID ($(date -Is))"
  echo "#include \"base_$BASE.fcl\""
  [ "$VARS" != "-" ] && for v in ${VARS//,/ }; do echo "#include \"v_$v.fcl\""; done
  echo "#include \"db_$DB.fcl\""
  echo "#include \"prof_services.fcl\""
} >| "$FCL"

THREADS=""
[ -n "$THR" ] && [ "$THR" != "1" ] && THREADS="--nthreads $THR --nschedules $THR"
SRC=-s; [[ $INPUT == *.txt ]] && SRC=-S
{
  echo "test=$ID arm=$ARM area=$AREA host=$(hostname -s) n=$N nskip=${NSKIP:-0} threads=${THR:-1}"
  echo "offline=$(git -C $AREA/Offline rev-parse --short HEAD 2>/dev/null) production=$(git -C $AREA/Production rev-parse --short HEAD 2>/dev/null)"
  echo "kinkal_lib=$(ls -l --time-style=+%F_%T $AREA/build/*/Offline/lib/libKinKal_Fit.so* 2>/dev/null | head -1 | awk '{print $6}')"
  echo "input=$INPUT"
  echo "cpu=$(grep -m1 'model name' /proc/cpuinfo | cut -d: -f2) load=$(cut -d' ' -f1-3 /proc/loadavg)"
} >| meta.txt
fhicl-dump -c "$FCL" >| job.cfg 2>&1 || { echo "FATAL: fhicl-dump failed, see $OUT/job.cfg"; exit 4; }

t0=$SECONDS
/usr/bin/time -v -o time.txt mu2e -c "$FCL" $SRC "$INPUT" -n "$N" ${NSKIP:+--nskip $NSKIP} $THREADS >| log.txt 2>&1
rc=$?
echo "exit=$rc wall=$((SECONDS-t0))s" >> meta.txt
ls -l *.art 2>/dev/null >> meta.txt
# keep only what the next stage needs: S:/U: inputs (reco.art of seed tests, dig.art of unpack) or KEEP=1
case " $(awk '{print $5}' "$HERE/tests.txt" | tr '\n' ' ') " in *" S:$ID "*|*" U:$ID "*) KEEP=1 ;; esac
[ "$KEEP" = 1 ] || rm -f -- *.art
echo "test=$ID exit=$rc out=$OUT"
echo RUN_PROFILE_DONE
exit $rc
